import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";

const repoRoot = process.cwd();
const linkedProjectPath = resolve(
  repoRoot,
  "supabase",
  ".temp",
  "linked-project.json",
);
const envFilePath = resolve(repoRoot, ".env.local");
const forceOverwrite = process.argv.includes("--force");

const readLinkedProjectRef = () => {
  const envProjectRef = process.env.SUPABASE_PROJECT_REF?.trim();

  if (envProjectRef) {
    return envProjectRef;
  }

  if (!existsSync(linkedProjectPath)) {
    throw new Error(
      "Missing supabase/.temp/linked-project.json. Set SUPABASE_PROJECT_REF or run `npx supabase link --project-ref <ref>` first.",
    );
  }

  const linkedProject = JSON.parse(readFileSync(linkedProjectPath, "utf8"));
  const projectRef =
    typeof linkedProject.ref === "string" ? linkedProject.ref.trim() : "";

  if (!projectRef) {
    throw new Error(
      "Could not read a Supabase project ref from supabase/.temp/linked-project.json.",
    );
  }

  return projectRef;
};

const listProjectApiKeys = (projectRef) => {
  const commandOutput = execSync(
    `npx supabase projects api-keys --project-ref ${projectRef} -o json`,
    {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "inherit"],
    },
  );

  return JSON.parse(commandOutput);
};

const projectRef = readLinkedProjectRef();
const apiKeys = listProjectApiKeys(projectRef);

const publishableKey =
  apiKeys.find((key) => key?.type === "publishable")?.api_key ?? null;
const anonKey =
  apiKeys.find(
    (key) =>
      key?.id === "anon" || (key?.type === "legacy" && key?.name === "anon"),
  )?.api_key ?? null;

if (!publishableKey && !anonKey) {
  throw new Error(
    `No publishable or anon API key was returned for project ${projectRef}.`,
  );
}

if (existsSync(envFilePath) && !forceOverwrite) {
  throw new Error(
    ".env.local already exists. Re-run with --force to replace it.",
  );
}

mkdirSync(resolve(repoRoot, "scripts"), { recursive: true });

const envLines = [
  "# Generated by npm run auth:env",
  `EXPO_PUBLIC_SUPABASE_URL=https://${projectRef}.supabase.co`,
];

if (publishableKey) {
  envLines.push(`EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${publishableKey}`);
}

if (anonKey) {
  envLines.push(`EXPO_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`);
}

writeFileSync(envFilePath, `${envLines.join("\n")}\n`, "utf8");

console.log(`Wrote ${envFilePath} for project ${projectRef}.`);
if (publishableKey) {
  console.log("Included EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY.");
}
if (anonKey) {
  console.log(
    "Included EXPO_PUBLIC_SUPABASE_ANON_KEY for legacy compatibility.",
  );
}
